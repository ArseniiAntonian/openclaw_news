r"""Паттерны для сбора пула кандидатов и для последующего эвала ретрива.

Единственный источник паттернов для всего эксперимента: и выгрузка пула, и
замер ретривера читают отсюда, чтобы они не разъехались.

Два набора, и разница между ними — принципиальная:

- `BROAD_NET` — широкий невод по общим словам темы. Им набирается пул
  документов, которые пойдут на разметку эталона.
- `OBJECT_PATTERNS` — ключевые слова объектов наблюдения из каталога банка.
  Это то, что мы **измеряем**, а не то, чем набираем пул.

Почему это разделено: если набрать пул ключевыми словами объектов и по нему
же мерить recall ключевых слов, получится 100% по построению — регекс найдёт
ровно то, что сам же в пул и положил. Пул обязан быть надмножеством: общий
невод ∪ ключевые слова. Тогда видно, что именно ключевые слова пропускают.

Пул = BROAD_NET ∪ OBJECT_PATTERNS (объединение, не пересечение).

## Про диалекты регекса

Паттерны написаны в питоновском синтаксисе с `\b` как границей слова.
В Postgres `\b` означает backspace, а граница слова — `\y`; перевод делает
`to_postgres()`. Всё остальное (`\w`, `(?:...)`, alternation) в обоих
диалектах совпадает. Регистронезависимость: `re.I` в питоне, `~*` в SQL.

## Про точность паттернов объектов

Полностью известен только объект 1 — он приведён в
`docs/architecture/observation_objects_context.md` целиком. У объектов 2–10
исходные регексы в документе обрезаны многоточием (сами `.xlsx` пользователь
удалил), поэтому они **восстановлены по алиасам и смыслу** и помечены
`approx=True`. Это надо помнить при чтении метрик: для approx-паттернов мы
меряем нашу реконструкцию, а не то, что реально пишет банк. Если оригиналы
однажды придут — правится здесь, в одном месте.
"""

from __future__ import annotations

import re
from dataclasses import dataclass, field


def to_postgres(pattern: str) -> str:
    """Питоновский регекс -> диалект Postgres.

    Единственное расхождение, которое нас касается: `\\b`. В питоне это
    граница слова, в Postgres -- backspace (граница слова там `\\y`).
    """
    return pattern.replace(r"\b", r"\y")


@dataclass(frozen=True)
class Pattern:
    key: str
    label: str
    regex: str
    approx: bool = False

    def compiled(self) -> re.Pattern[str]:
        return re.compile(self.regex, re.IGNORECASE | re.UNICODE)


@dataclass(frozen=True)
class ObjectPattern(Pattern):
    object_id: int = 0
    negative: str | None = field(default=None)


