def pool_patterns() -> tuple[Pattern, ...]:
    """Всё, чем набирается пул: широкий невод + ключевые слова объектов."""
    return BROAD_NET + OBJECT_PATTERNS


def pool_sql_regex() -> str:
    """Один альтернированный регекс под Postgres `~*` для отбора пула."""
    return "|".join(f"(?:{to_postgres(p.regex)})" for p in pool_patterns())