# ---------------------------------------------------------------------------
# Контрольные паттерны: однозначные подстроки для проверки качества разметки.
#
# Это НЕ измеряемые паттерны и не замена каталогу. Контроль исходит из того,
# что срабатывание почти наверняка означает релевантность, а у каталожного
# регекса объекта 1 такого свойства нет: альтернатива `кандинск` ловит
# Василия Кандинского (выставки, живопись) наравне с моделью Сбера -- это
# видно в данных первого прогона разметки. Поэтому контроль строится на
# брендовой строке без двусмысленностей.
#
# Сам каталожный регекс при этом не правится: подмена паттерна банка на свой
# означала бы, что эксперимент меряет мою редактуру, а не методику заказчика.
# Неоднозначность `кандинск` идёт в отчёт как отдельная находка.
# ---------------------------------------------------------------------------

